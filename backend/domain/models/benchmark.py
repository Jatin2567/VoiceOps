"""Domain models for Voice AI benchmarking."""
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4

from pydantic import BaseModel, Field


class PipelineMode(str, Enum):
    """Architectural topology mode for the voice pipeline."""
    CASCADE = "cascade"   # STT (Groq Whisper) -> LLM (Groq LLM) -> TTS (Edge-TTS)
    HYBRID = "hybrid"     # Groq + Edge-TTS with deterministic tool guardrails


class BenchmarkStatus(str, Enum):
    """Lifecycle status of a benchmark execution."""
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


class AudioInputSource(str, Enum):
    """Source descriptor for input audio."""
    FILE = "file"
    STREAM = "stream"


class LatencyBreakdown(BaseModel):
    """Granular latency distribution across the pipeline stages in milliseconds."""
    stt_latency_ms: Optional[float] = Field(
        default=None,
        description="Time taken by STT to produce the transcript from speech end"
    )
    llm_ttft_ms: Optional[float] = Field(
        default=None,
        description="Time-to-first-token generated by the LLM"
    )
    tts_ttfb_ms: Optional[float] = Field(
        default=None,
        description="Time-to-first-audio-byte from TTS synthesis start"
    )
    guardrail_overhead_ms: Optional[float] = Field(
        default=None,
        description="Deterministic policy sidecar evaluation latency"
    )
    total_turn_latency_ms: Optional[float] = Field(
        default=None,
        description="Total duration from speech end to complete synthesized speech playback"
    )


class BenchmarkRequest(BaseModel):
    """Domain request for initiating a pipeline benchmark run."""
    trace_id: str = Field(
        default_factory=lambda: str(uuid4()),
        description="Unique distributed tracing identifier for this turn"
    )
    mode: PipelineMode = Field(
        default=PipelineMode.CASCADE,
        description="Target pipeline topology to benchmark"
    )
    audio_file_path: Optional[str] = Field(
        default=None,
        description="Path to local or static .wav audio file for discrete playback"
    )
    audio_url: Optional[str] = Field(
        default=None,
        description="Optional remote URL to stream audio from"
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Logical conversation session ID"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary caller metadata or tags"
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the benchmark request was initiated"
    )


class BenchmarkResult(BaseModel):
    """Aggregated benchmark outcome and latency observability record."""
    trace_id: str = Field(
        ...,
        description="Matching trace ID of the benchmark run"
    )
    mode: PipelineMode = Field(
        ...,
        description="Topology tested"
    )
    status: BenchmarkStatus = Field(
        default=BenchmarkStatus.PENDING,
        description="Current execution status"
    )
    ttfa_ms: Optional[float] = Field(
        default=None,
        description="Time-to-First-Audio latency (T1 - T0) in milliseconds"
    )
    breakdown: LatencyBreakdown = Field(
        default_factory=LatencyBreakdown,
        description="Stage-specific latency breakdown"
    )
    transcription: Optional[str] = Field(
        default=None,
        description="User speech transcription text"
    )
    response_text: Optional[str] = Field(
        default=None,
        description="Agent text response"
    )
    guardrail_violations: List[str] = Field(
        default_factory=list,
        description="List of detected policy violations or blocked attempts"
    )
    interception_count: int = Field(
        default=0,
        description="Number of function calls intercepted by sidecar"
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Error details if execution failed"
    )
    completed_at: Optional[datetime] = Field(
        default=None,
        description="Timestamp of pipeline completion"
    )
